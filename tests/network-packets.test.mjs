import { packetExample, internetChecksum } from "../js/network-packets.mjs";
import { protocolFacts } from "../js/network-facts.mjs";
import { guidedLessons } from "../js/network-guided.mjs";

export function runNetworkPacketTests() {
    let passed = 0;
    const assert = (condition, label) => { if (!condition) throw new Error(label); passed++; };
    assert(Object.keys(protocolFacts).length === 39, "Every lesson has original fact rows");
    for (const id of Object.keys(guidedLessons)) {
        assert(protocolFacts[id].ports.length > 0 && protocolFacts[id].format.length > 10 && protocolFacts[id].operations.length > 10, `${id} facts are complete`);
    }
    assert(internetChecksum(Uint8Array.of(0, 1, 0xf2, 3, 0xf4, 0xf5, 0xf6, 0xf7)) === 0x220d, "RFC 1071 checksum vector");
    for (const protocol of ["DHCP DISCOVER", "DHCP OFFER", "DHCP REQUEST", "DHCP ACK", "DNS query", "DNS answer", "TCP SYN", "TCP SYN-ACK", "TCP ACK", "HTTP GET", "HTTP 200", "ICMP Echo Request", "ICMP Echo Reply"]) {
        const step = { protocol, phase: "", summary: "" };
        const example = packetExample(step);
        assert(example?.bytes.length > 40, `${protocol} has real generated bytes`);
        assert(example.note.includes("synthetic") && example.note.includes("omitted"), `${protocol} explicitly identifies example and omissions`);
        const bytes = example.bytes;
        const ip = bytes.slice(14, 34);
        const view = new DataView(bytes.buffer);
        assert(ip[0] === 0x45 && view.getUint16(16) === bytes.length - 14, `${protocol} IPv4 length matches bytes`);
        assert(internetChecksum(ip) === 0, `${protocol} IPv4 checksum verifies`);
        assert(view.getUint16(12) === 0x0800, `${protocol} Ethernet type identifies IPv4`);
        const segment = bytes.slice(34);
        if (ip[9] === 1) assert(internetChecksum(segment) === 0, `${protocol} ICMP checksum verifies`);
        else {
            const pseudo = new Uint8Array(12 + segment.length);
            pseudo.set(ip.slice(12, 20)); pseudo[9] = ip[9];
            new DataView(pseudo.buffer).setUint16(10, segment.length); pseudo.set(segment, 12);
            assert(internetChecksum(pseudo) === 0, `${protocol} transport pseudo-header checksum verifies`);
            if (ip[9] === 17) assert(view.getUint16(38) === segment.length, `${protocol} UDP length matches payload`);
            else assert(bytes[46] >>> 4 === 5, `${protocol} TCP header is 20 bytes`);
        }
        assert(example.sections.reduce((sum, section) => sum + section.length, 0) === bytes.length, `${protocol} decoded layers account for every byte`);
        for (const section of example.sections) {
            assert(section.start + section.length <= bytes.length, `${protocol} ${section.name} range is bounded`);
            for (const field of section.fields) {
                assert(field.start >= section.start && field.start + field.length <= section.start + section.length, `${protocol} field ${field.label} highlights its own section`);
            }
        }
        if (protocol.startsWith("DHCP")) {
            assert(bytes.slice(0, 6).every(byte => byte === 255), `${protocol} Ethernet broadcast is accurate`);
            assert(bytes.slice(30, 34).every(byte => byte === 255), `${protocol} IPv4 broadcast is accurate`);
            assert(bytes[278] === 99 && bytes[281] === 99, `${protocol} DHCP magic cookie is present`);
            assert(bytes[282] === 53 && bytes[283] === 1, `${protocol} DHCP message type option is encoded`);
            assert(segment.length === 308, `${protocol} BOOTP-compatible payload includes minimum padding`);
        }
        if (protocol.startsWith("DNS")) {
            assert(view.getUint16(42) === 0x4001, `${protocol} transaction ID matches its decoded field`);
            assert(view.getUint16(46) === 1, `${protocol} has one question`);
            assert(view.getUint16(48) === (protocol === "DNS answer" ? 1 : 0), `${protocol} answer count matches payload`);
        }
        if (protocol.startsWith("HTTP")) {
            const message = new TextDecoder().decode(bytes.slice(54));
            assert(message.includes("\r\n\r\n"), `${protocol} uses CRLF header termination`);
            if (protocol === "HTTP 200") assert(message.split("\r\n\r\n")[1].length === 5, "HTTP Content-Length matches encoded body");
        }
        assert(packetExample(step).bytes !== bytes, `${protocol} examples return fresh mutable bytes`);
    }
    for (const protocol of ["TLS encrypted server flight", "HTTPS request", "DoH POST", "DNSSEC local validation", "QUIC Initial", "DNS root referral", "DHCP timeout"]) {
        assert(packetExample({ protocol, phase: "", summary: "" }) === null, `${protocol} never receives a fabricated wire dump`);
    }
    assert(packetExample({ protocol: "DNS query", phase: "", summary: "", error: true }) === null, "Failed events never generate success-shaped examples");
    for (const step of [
        { protocol: "DISCOVER", family: "DHCP", summary: "" },
        { protocol: "TCP", summary: "SYN / request a connection on port 80" },
        { protocol: "HTTP", summary: "GET / HTTP/1.1" },
        { protocol: "DNS recursive query", summary: "" }
    ]) assert(packetExample(step)?.bytes.length > 40, "Sandbox and recursive-query naming share the same safe encoders");
    return { passed, message: `${passed} packet/fact model assertions passed.` };
}

if (typeof window === "undefined") console.log(runNetworkPacketTests().message);
