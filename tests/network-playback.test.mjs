export async function runNetworkPlaybackTests() {
    let passed = 0;
    const $ = id => document.getElementById(id);
    const wait = delay => new Promise(resolve => setTimeout(resolve, delay));
    const assert = (condition, label) => { if (!condition) throw new Error(label); passed++; };
    const change = (id, value) => { $(id).value = value; $(id).dispatchEvent(new Event("change")); };
    const untilIdle = async () => {
        for (let count = 0; count < 650 && $("network").dataset.playback === "playing"; count++) await wait(50);
        assert($("network").dataset.playback !== "playing", "Bounded playback finishes");
    };
    location.hash = "#network"; window.dispatchEvent(new HashChangeEvent("hashchange"));
    change("network-mode", "guided");
    $("protocol-search").value = ""; $("protocol-search").dispatchEvent(new Event("input"));
    document.querySelector('[data-category="all"]').click();
    document.querySelector('#protocol-picker [data-protocol="http"]').click();
    change("network-speed", "600");
    change("network-step-unit", "hop");
    $("network-show-upcoming").checked = false;
    $("network-show-upcoming").dispatchEvent(new Event("change"));
    assert(!document.querySelector("#packet-rows tr:not([hidden])") && !$("packet-empty").hidden, "Packet Flow starts empty until an exchange actually begins");
    $("network-show-upcoming").click();
    assert(document.querySelectorAll("#packet-rows tr:not([hidden])").length === 7, "Upcoming messages remain available as an explicit teaching preview");
    $("network-show-upcoming").click();
    $("network-step").click(); $("network-step").click();
    let packet = document.querySelector(".network-packet");
    assert(document.querySelectorAll(".device:not(.scene-outside)").length === 3, "Follow packet retains the client, gateway and resolver for the whole DNS phase");
    const camera = $("topology-board").style.transform;
    assert(!$("protocol-phase-content").hidden && $("phase-live-name").textContent === $("scene-packet-name").textContent, "Starting the exchange opens synchronized step details");
    $("network-follow-scene").click();
    assert(document.querySelector(".network-packet") === packet, "Changing camera scope does not replace or deliver the in-flight packet");
    assert(!document.querySelector(".device.scene-outside"), "Turning off follow restores the full topology");
    $("network-follow-scene").click();
    $("network-replay").click(); $("network-step").click(); $("network-step").click();
    packet = document.querySelector(".network-packet");
    if (!matchMedia("(prefers-reduced-motion: reduce)").matches) {
        assert(packet.getAnimations()[0].playState === "running", "Manual Step starts real travel");
        const row = document.querySelector("#packet-rows .packet-current");
        assert(row.dataset.state === "transit" && row.querySelector(".packet-live-state").textContent === "IN TRANSIT", "Packet Flow enters transit at the same moment as the scene");
        assert($("phase-live-state").textContent === $("scene-packet-state").textContent && $("packet-status").textContent.includes("Laptop → Gateway"), "Scene, step details and status describe the same live forwarding hop");
        const progress = Number(row.style.getPropertyValue("--message-progress"));
        await wait(100);
        assert(Number(row.style.getPropertyValue("--message-progress")) > progress, "Message progress follows actual packet animation time");
        for (let count = 0; count < 40 && $("scene-packet-state").textContent === "IN TRANSIT"; count++) await wait(50);
        assert($("scene-packet-state").textContent === "PROCESSING", "Manual Step completes travel before holding at the receiver");
        assert(row.dataset.state === "processing" && row.querySelector(".packet-live-route").textContent.includes("At Gateway"), "Arrival updates Packet Flow to processing at the real receiving actor");
        assert(!row.classList.contains("packet-visited"), "An intermediate receiving hop does not prematurely mark the whole message delivered");
        $("network-step").click();
        assert($("topology-board").style.transform === camera, "Camera framing stays stable while the message moves through the same phase");
        assert(!row.classList.contains("packet-visited"), "The final hop is not marked delivered while still traveling");
        for (let count = 0; count < 40 && $("scene-packet-state").textContent === "IN TRANSIT"; count++) await wait(50);
        assert(row.classList.contains("packet-visited") && row.querySelector(".packet-live-route").textContent.includes("At Resolver"), "Logical message is delivered only when its final hop arrives");
        $("network-replay").click(); $("network-step").click();
        $("network-play").click();
        await wait(100);
        $("network-play").click();
        packet = document.querySelector(".network-packet");
        await packet.getAnimations()[0].ready;
        const transform = getComputedStyle(packet).transform;
        const index = $("network-progress").value;
        await wait(250);
        assert(getComputedStyle(packet).transform === transform, "Pause freezes the packet at its actual position rather than snapping it to the destination");
        assert($("network-progress").value === index && $("scene-packet-state").textContent === "PAUSED", "Pause freezes the teaching clock");
        const liveRow = document.querySelector("#packet-rows .packet-current");
        const pausedProgress = liveRow.style.getPropertyValue("--message-progress");
        assert(liveRow.dataset.state === "paused" && $("phase-live-state").textContent === "PAUSED" && $("packet-live-indicator").textContent === "PAUSED", "Pause is reflected in Packet Flow, step details and live indicator");
        await wait(100);
        assert(liveRow.style.getPropertyValue("--message-progress") === pausedProgress, "Packet Flow progress freezes with the packet");
        change("network-table-unit", "hop");
        assert(document.querySelector("#packet-rows .packet-current").dataset.state === "paused", "Every-hop table preserves the paused live state");
        change("network-table-unit", "message");
        assert(document.querySelector("#packet-rows .packet-current .packet-live-route").textContent.includes("Laptop → Gateway"), "Returning to logical messages preserves the active physical route");
        $("network-play").click();
        const resumeTime = packet.getAnimations()[0].currentTime;
        await wait(90);
        assert($("network-progress").value === index && packet.getAnimations()[0].currentTime > resumeTime, "Resume continues the same hop's timeline, including any camera-yield delay, without skipping or restarting");
        assert(document.querySelector("#packet-rows .packet-current").dataset.state === "transit" && $("phase-live-state").textContent === "IN TRANSIT", "Resume restores all live surfaces together");
        $("network-play").click();
    }
    $("network-replay").click();
    change("network-speed", "300");
    change("network-step-unit", "message");
    $("network-step").click();
    await untilIdle();
    assert($("network-progress").value === 3, "Message Step animates every forwarding hop and holds at the message boundary");
    assert($("scene-packet-state").textContent === "PROCESSING", "The last hop of a message is allowed to arrive");
    $("network-step").click();
    await untilIdle();
    assert($("network-progress").value === 6 && $("scene-packet-state").textContent === "PROCESSING", "The return message reaches its own receiver");
    $("network-replay").click();
    change("network-speed", "1200");
    $("network-play").click();
    for (let count = 0; count < 400 && !($("network-progress").value === 2 && $("scene-packet-state").textContent === "PROCESSING"); count++) await wait(50);
    assert($("network-progress").value === 2, "A receiving-node hold is available before forwarding");
    $("network-play").click();
    $("network-play").click();
    await wait(80);
    assert($("network-progress").value === 2 && !document.querySelector(".network-packet").getAnimations().some(animation => animation.playState === "running"), "Resuming a processing hold does not replay the already delivered packet");
    $("network-play").click();
    $("network-replay").click();
    change("network-speed", "300");
    change("network-step-unit", "phase");
    $("network-step").click();
    await untilIdle();
    assert($("network-progress").value === 6, "Phase Step holds only after all messages in the phase");
    $("network-replay").click();
    $("network-play").click();
    for (let count = 0; count < 350 && $("network-progress").value <= 6; count++) await wait(50);
    assert($("network-progress").value > 6, "Play continues across message and phase boundaries regardless of Step unit");
    change("network-speed", "600");
    assert($("network").dataset.playback === "playing", "Changing speed preserves active playback");
    $("network-play").click();
    const paused = $("network-progress").value;
    await wait(750);
    assert($("network-progress").value === paused, "Speed changes leave no orphaned playback timer");
    $("network-replay").click();
    change("network-speed", "300");
    $("network-play").click();
    await untilIdle();
    assert($("network-progress").value === $("network-progress").max, "Continuous playback finishes the entire lesson");
    assert($("scene-packet-state").textContent === "PROCESSING" && document.querySelector(".device.processing"), "The final packet finishes its animation before playback stops");
    assert($("network-play").disabled, "Completed playback exposes a clear reset action rather than a dead Play button");
    assert([...document.querySelectorAll("#packet-rows tr")].every(row => row.classList.contains("packet-visited")), "Every Packet Flow message is delivered after full playback");
    assert($("phase-live-state").textContent === $("scene-packet-state").textContent, "Final details remain synchronized after the teaching clock stops");
    assert(document.querySelectorAll("[data-theme-toggle]").length === 1 && document.querySelector(".lab-header [data-theme-toggle]"), "Only the global top-right theme control remains");
    assert(document.querySelectorAll("#packet-rows tr:first-child td").length === 6, "Packet table separates source, destination, protocol and explanation");
    assert([...$("packet-legend").children].map(chip => chip.textContent).join(",") === "DNS,TCP,HTTP", "Legend describes only families present in this lesson");
    $("network-replay").click();
    assert($("phase-live-card").hidden && $("packet-live-indicator").textContent === "READY", "Replay clears stale live details and restores ready state");
    change("network-step-unit", "hop");
    change("network-speed", "600");
    return { passed, message: `${passed} packet playback assertions passed.` };
}
