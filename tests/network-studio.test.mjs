export async function runNetworkStudioTests() {
    let passed = 0;
    const $ = id => document.getElementById(id);
    const assert = (condition, label) => { if (!condition) throw new Error(label); passed++; };
    const select = (id, value) => { $(id).value = value; $(id).dispatchEvent(new Event("change")); };
    const pick = id => document.querySelector(`#protocol-picker [data-protocol="${id}"]`).click();
    const finish = () => { while (!$("network-step").disabled) $("network-step").click(); };
    location.hash = "#network";
    window.dispatchEvent(new HashChangeEvent("hashchange"));
    select("network-mode", "guided");
    $("protocol-search").value = "";
    $("protocol-search").dispatchEvent(new Event("input"));
    document.querySelector('[data-category="all"]').click();
    assert($("protocol-picker").children.length === 39, "All 39 guided lessons are available");
    const ids = [...$("protocol-picker").querySelectorAll("[data-protocol]")].map(button => button.dataset.protocol);
    for (const id of ids) {
        pick(id);
        assert($("packet-rows").children.length > 0, `${id} prepares a real guided exchange`);
        assert($("protocol-description").textContent.length > 30 && $("protocol-references").children.length > 0, `${id} has overview and standards references`);
        assert($("network-progress").value === 0, `${id} starts without invented progress`);
        $("network-step").click();
        assert($("packet-rows").querySelectorAll(".packet-current").length === 1, `${id} highlights the inspected hop`);
        assert($("packet-explanation").textContent.length > 10, `${id} explains the active hop`);
        $("sequence-view").click();
        assert(!$("network-sequence-view").hidden && $("network-map-view").hidden, `${id} switches to sequence view`);
        assert($("network-sequence").querySelectorAll(".sequence-lifeline").length >= 2, `${id} has meaningful sequence actors`);
        finish();
        assert($("network-progress").value === $("network-progress").max, `${id} completes its scripted exchange`);
        $("network-replay").click();
        assert($("network-progress").value === 0 && !$("network-play").disabled, `${id} can replay`);
        $("network-view").click();
    }
    document.querySelector('[data-category="security"]').click();
    assert($("protocol-picker").children.length > 0 && $("protocol-picker").children.length < 39, "Security filter narrows the library");
    $("protocol-search").value = "no matching protocol";
    $("protocol-search").dispatchEvent(new Event("input"));
    assert(!$("protocol-empty").hidden && !$("protocol-picker").children.length, "Empty searches are explicit, not fake lessons");
    document.querySelector('[data-category="all"]').click();
    $("protocol-search").value = "443";
    $("protocol-search").dispatchEvent(new Event("input"));
    assert($("protocol-picker").children.length > 0, "Port search finds lessons");
    $("protocol-search").value = "";
    $("protocol-search").dispatchEvent(new Event("input"));
    select("network-mode", "sandbox");
    assert($("protocol-picker").children.length === 5 && !$("source-client").disabled, "Sandbox exposes only its five topology-aware lessons");
    $("network-reset").click();
    pick("dhcp");
    $("run-protocol").click();
    $("network-step").click();
    $("network-stop").click();
    $("run-web").click();
    assert($("network-status").classList.contains("error") && !$("packet-rows").children.length, "Cancelled DHCP does not issue a lease");
    $("run-dhcp").click();
    finish();
    assert([...document.querySelectorAll(".device")].some(device => device.textContent.includes("192.168.10.100")), "DHCP commits lease only when complete");
    $("network-back").click();
    assert(![...document.querySelectorAll(".device")].some(device => device.textContent.includes("192.168.10.100")), "Rewinding a new DHCP exchange removes its uncommitted lease");
    finish();
    $("run-web").click();
    assert($("packet-rows").children.length > 0, "Completed DHCP enables HTTP");
    finish();
    assert(!$("network-status").classList.contains("error"), "HTTP succeeds on office topology");
    pick("https");
    $("run-protocol").click();
    const phase = document.querySelector('#protocol-phases [data-phase="TLS"]');
    phase.click();
    assert($("packet-status").textContent.includes("TLS"), "Phase navigation seeks into TLS handshake");
    $("network-replay").click();
    const node = document.querySelector(".device");
    const before = node.style.left;
    node.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowRight", bubbles: true }));
    assert(node.style.left !== before, "Keyboard repositioning remains supported");
    const nodeLeft = node.style.left;
    select("network-mode", "guided");
    pick("dns");
    select("network-mode", "sandbox");
    assert(document.querySelector(".device").style.left === nodeLeft, "Guided lessons do not overwrite edited sandbox positions");
    $("run-web").click();
    assert($("packet-rows").children.length > 0, "Sandbox leases survive a guided-mode visit");
    $("firewall-on").checked = true;
    $("firewall-on").dispatchEvent(new Event("change"));
    $("run-web").click();
    finish();
    assert($("network-status").classList.contains("error") && $("packet-explanation").textContent.includes("Firewall"), "Firewall failure is visible in the overview and table");
    $("firewall-on").checked = false;
    $("firewall-on").dispatchEvent(new Event("change"));
    $("network-reset").click();
    const count = document.querySelectorAll(".device").length;
    $("device-type").value = "phone";
    $("add-device").click();
    assert(document.querySelectorAll(".device").length === count + 1, "Sandbox still adds devices");
    const board = $("topology-board").getBoundingClientRect();
    const transfer = new DataTransfer();
    transfer.setData("application/x-lab-device", "client");
    $("topology-board").dispatchEvent(new DragEvent("drop", {
        bubbles: true, cancelable: true, dataTransfer: transfer,
        clientX: board.left + board.width * 400 / 760, clientY: board.top + board.height * 340 / 440
    }));
    const dropped = document.querySelector(".device:last-child");
    assert(Math.abs(parseFloat(dropped.style.left) - 343) <= 1 && Math.abs(parseFloat(dropped.style.top) - 302) <= 1, "Palette drops account for the scaled diagram coordinates");
    const oldFocus = $("network-focus").getAttribute("aria-pressed") === "true";
    if (oldFocus) $("network-focus").click();
    $("network-focus").click();
    assert($("network").classList.contains("diagram-focus"), "Diagram focus hides secondary panels");
    $("network-focus").click();
    select("network-mode", "guided");
    pick("http");
    $("network-play").click();
    document.dispatchEvent(new Event("visibilitychange"));
    window.dispatchEvent(new PageTransitionEvent("pagehide"));
    assert($("network-play").textContent === "Play", "Page lifecycle stops playback");
    const resources = performance.getEntriesByType("resource").length;
    $("network-step").click();
    assert(performance.getEntriesByType("resource").length === resources, "Simulation steps make no network calls");
    $("network-replay").click();
    return { passed, message: `${passed} Network Studio UI assertions passed.` };
}
