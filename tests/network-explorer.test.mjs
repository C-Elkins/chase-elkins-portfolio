import { guidedLessons } from "../js/network-guided.mjs";

export async function runNetworkExplorerTests() {
    let passed = 0;
    const $ = id => document.getElementById(id);
    const assert = (condition, label) => { if (!condition) throw new Error(label); passed++; };
    const settle = () => new Promise(resolve => setTimeout(resolve, 30));
    const finishStep = async () => {
        for (let count = 0; count < 1000 && $("network").dataset.playback === "playing"; count++) await settle();
        assert($("network").dataset.playback !== "playing", "Selected step finishes animating");
    };
    const key = (value, target = document.body, modifiers = {}) => {
        target.dispatchEvent(new KeyboardEvent("keydown", { key: value, bubbles: true, cancelable: true, ...modifiers }));
    };
    const pick = id => document.querySelector(`#protocol-picker [data-protocol="${id}"]`).click();
    const change = (id, value) => { $(id).value = value; $(id).dispatchEvent(new Event("change")); };
    const close = async id => { $(id).close(); await settle(); };
    location.hash = "#network";
    window.dispatchEvent(new HashChangeEvent("hashchange"));
    change("network-mode", "guided");
    $("network-step-unit").value = "hop";
    document.querySelector('[data-category="all"]').click();
    $("protocol-search").value = ""; $("protocol-search").dispatchEvent(new Event("input"));
    $("course-reset").click();
    assert(document.body.classList.contains("network-app"), "Network opens as compact workspace");
    $("network-compact").click();
    assert(!document.body.classList.contains("network-app"), "Lab introduction can be restored");
    $("network-compact").click();
    const layers = ["PHYSICAL", "DATA LINK", "NETWORK", "TRANSPORT", "SESSION", "PRESENTATION", "APPLICATION"];
    for (const [id, lesson] of Object.entries(guidedLessons)) {
        pick(id);
        const chips = [...$("network-layers").children];
        assert(chips.length === 7 && chips.map(chip => chip.textContent).join("") === "1234567", `${id} shows all seven ordered OSI indicators`);
        assert(chips.filter(chip => chip.classList.contains("layer-current")).length === 1, `${id} has one primary OSI focus`);
        assert(chips[lesson.layerIndex - 1].classList.contains("layer-current"), `${id} highlights the lesson's actual layer`);
        assert($("network-layer-name").textContent === layers[lesson.layerIndex - 1], `${id} names that layer in the header`);
        assert($("network-layers").getAttribute("aria-label").includes(lesson.layer), `${id} accessible label preserves cross-layer nuances`);
        assert($("protocol-ports").textContent.length > 0 && ["protocol-format", "protocol-operations"].every(id => $(id).textContent.length > 10), `${id} has full overview facts`);
        assert(document.querySelectorAll("#protocol-picker [data-phase]").length === lesson.phases.length, `${id} active library expands all phases`);
        assert([...document.querySelectorAll("#protocol-picker [data-phase]")].every(button => !button.disabled), `${id} phases are enabled after preparation`);
        $("network-inspect").click();
        assert($("protocol-inspector").open && $("inspector-summary").textContent.length > 10, `${id} has an actual message inspector`);
        assert($("inspector-fields").children.length === 6, `${id} inspector documents route, semantics and size/timing limits`);
        await close("protocol-inspector");
    }
    pick("http");
    assert($("packet-rows").children.length === 7, "Packet table starts with logical messages, not duplicated forwarding rows");
    change("network-table-unit", "hop");
    assert($("packet-rows").children.length === $("network-progress").max, "Every forwarding hop can still be inspected");
    document.querySelector("#packet-rows button").click();
    assert($("protocol-inspector").open && $("network-progress").value === 1, "Hop-row inspection preserves the exact selected hop");
    await close("protocol-inspector");
    change("network-table-unit", "message");
    document.querySelector("#packet-rows button").click();
    assert($("protocol-inspector").open && $("network-progress").value === 3, "Message-row inspection seeks to a logical message boundary");
    await close("protocol-inspector");
    $("network-osi-guide").click();
    assert($("protocol-osi").open && $("osi-current").textContent.includes("HTTP"), "OSI guide follows selected lesson");
    await close("protocol-osi");
    key("k", document.body, { ctrlKey: true });
    assert($("protocol-command").open && document.activeElement === $("command-query"), "Ctrl K opens focused command search");
    $("command-query").value = "443"; $("command-query").dispatchEvent(new Event("input"));
    assert($("command-results").children.length > 0, "Command search indexes port metadata");
    $("command-query").value = "authenticate"; $("command-query").dispatchEvent(new Event("input"));
    assert([...$("command-results").children].some(option => option.textContent.includes("Jump to")), "Command search indexes lesson phases");
    key("ArrowDown", $("command-query"));
    assert($("command-query").getAttribute("aria-activedescendant") === $("command-results").children[1].id, "Arrow keys update active search result accessibly");
    $("command-query").value = "no such protocol <script>"; $("command-query").dispatchEvent(new Event("input"));
    key("Enter", $("command-query"));
    assert($("protocol-command").open && $("command-results").children.length === 0, "No-result Enter does nothing and input stays literal");
    $("command-query").value = "DHCP / impossible"; $("command-query").dispatchEvent(new Event("input"));
    $("command-query").value = "DHCP Acknowledge"; $("command-query").dispatchEvent(new Event("input"));
    assert($("command-results").children.length === 1, "Exact protocol-phase search finds a unique phase");
    key("Enter", $("command-query"));
    await settle();
    assert(!$("protocol-command").open && $("protocol-name").textContent === "DHCP" && $("packet-status").textContent.includes("Acknowledge"), "Enter opens matching guided lesson at selected phase");
    $("network-library").click();
    assert($("protocol-drawer").open && $("protocol-drawer-content").contains($("protocol-picker")), "Library drawer moves the real searchable library, not a duplicate");
    const phaseToggle = document.querySelector(".library-phase-toggle");
    phaseToggle.click();
    assert(document.querySelector(".library-phases").hidden, "Nested phases can collapse");
    phaseToggle.click();
    document.querySelector('#protocol-picker [data-phase="Offer"]').click();
    for (let count = 0; count < 40 && !document.querySelector(".network-layout").contains($("protocol-picker")); count++) await settle();
    assert(!$("protocol-drawer").open && document.querySelector(".network-layout").contains($("protocol-picker")), "Phase selection closes drawer and restores inline library");
    assert($("packet-status").textContent.includes("Offer"), "Nested phase selection actually seeks");
    assert(!$("protocol-phase-content").hidden && $("protocol-phase-messages").children.length > 0, "Phase navigation opens a real instructional detail view");
    $("protocol-overview-show").click();
    assert(!$("protocol-overview-content").hidden, "Overview toggle returns to complete protocol facts");
    pick("http");
    $("network-replay").click();
    change("network-speed", "300");
    $("network-step-unit").value = "message";
    $("network-step").click();
    await finishStep();
    assert($("network-progress").value === 3, "Whole-message stepping advances every forwarding hop of one message");
    $("network-step").click(); await finishStep(); $("network-back").click();
    assert($("network-progress").value === 3, "Previous-message stepping returns to previous boundary");
    $("network-replay").click(); $("network-step-unit").value = "phase";
    $("network-step").click();
    await finishStep();
    assert($("network-progress").value === 6, "Phase stepping advances both DNS exchanges");
    $("network-back").click();
    assert($("network-progress").value === 0, "Previous-phase stepping returns to start");
    $("network-step-unit").value = "hop";
    const before = $("network-progress").value;
    key("ArrowRight", $("protocol-search"));
    assert($("network-progress").value === before, "Typing fields are never hijacked by shortcuts");
    key("ArrowRight");
    assert($("network-progress").value === before + 1, "Next-step shortcut works outside fields");
    key("s"); assert($("network-step-unit").value === "message", "S cycles to logical-message stepping");
    key("v"); assert(!$("network-sequence-view").hidden, "V switches views");
    key("v"); assert(!$("network-map-view").hidden, "V switches back");
    key("?"); assert($("protocol-shortcuts").open, "Question mark opens shortcuts guide");
    await close("protocol-shortcuts");
    $("network-replay").click();
    document.querySelector("#message-flow button").click();
    assert($("protocol-inspector").open && $("inspector-title").textContent === "DNS query", "Logical-message strip opens inspector");
    assert(!$("inspector-wire").hidden && $("wire-bytes").querySelectorAll("[data-byte]").length > 40, "Supported message renders actual encoded example bytes");
    $("inspector-wire").open = true;
    document.querySelector("#wire-fields button").click();
    assert($("wire-bytes").querySelectorAll(".byte-selected").length === 12, "Decoded Ethernet address field highlights exactly its 12 bytes");
    key("ArrowRight", $("inspect-next"));
    assert($("inspector-title").textContent === "DNS answer", "Inspector arrow keys select next logical message");
    key("ArrowLeft", $("inspect-previous"));
    assert($("inspector-title").textContent === "DNS query" && $("inspect-previous").disabled, "Inspector previous boundary is safe");
    await close("protocol-inspector");
    pick("https");
    const encrypted = [...document.querySelectorAll("#message-flow button")].find(button => button.textContent.includes("encrypted server"));
    encrypted.click();
    assert($("inspector-wire").hidden && !$("inspector-unavailable").hidden && !$("wire-bytes").children.length, "Encrypted aggregate has no bogus bytes or stale dump");
    await close("protocol-inspector");
    $("course-reset").click(); pick("dhcp"); change("network-step-unit", "message"); change("network-speed", "300");
    while (!$("network-step").disabled) { $("network-step").click(); await finishStep(); }
    assert($("course-progress").value === 1, "Exploring all logical messages completes one visit lesson");
    $("network-replay").click(); pick("http"); pick("dhcp");
    assert(document.querySelector('#protocol-picker [data-protocol="dhcp"]').dataset.progress === "complete", "Visit progress survives replay and protocol switching");
    $("course-reset").click();
    assert($("course-progress").value === 0 && $("network-progress").value === 0, "Reset clears visit progress and current trace position");
    change("network-step-unit", "hop");
    change("network-mode", "sandbox"); $("network-reset").click();
    $("run-dhcp").click();
    while (!$("network-step").disabled) $("network-step").click();
    $("course-reset").click();
    assert([...document.querySelectorAll(".device-ip")].some(node => node.textContent === "192.168.10.100"), "Resetting guided progress never revokes a sandbox DHCP lease");
    $("network-command").click();
    $("command-query").value = "WireGuard"; $("command-query").dispatchEvent(new Event("input"));
    key("Enter", $("command-query")); await settle();
    assert($("network-mode").value === "guided" && $("protocol-name").textContent === "WireGuard", "Searching outside sandbox inventory explicitly switches to guided");
    change("network-mode", "sandbox");
    assert(document.querySelectorAll(".device").length === 7, "Search visit preserves editable sandbox topology");
    change("network-mode", "guided"); pick("dhcp");
    $("network-speed").value = "300"; $("network-step-unit").value = "message";
    $("network-replay").click(); $("network-step").click();
    await finishStep();
    assert($("network-progress").value === 3 && $("network-play").textContent === "Play", "One-message playback animates hops then holds at its routing boundary");
    $("network-step-unit").value = "hop"; $("network-speed").value = "600";
    $("network-replay").click();
    location.hash = "#crypto"; window.dispatchEvent(new HashChangeEvent("hashchange"));
    key("n");
    assert($("protocol-name").textContent === "DHCP" && !document.body.classList.contains("network-app"), "Network shortcuts/compact layout do not affect other labs");
    location.hash = "#network"; window.dispatchEvent(new HashChangeEvent("hashchange"));
    return { passed, message: `${passed} explorer navigation and OSI assertions passed.` };
}
